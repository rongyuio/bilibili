// Command genall 扫描业务子包，生成 bili 包的聚合入口。
//
// 它只认一种子包：目录下有 client.go，且声明了
//
//	func New(*bilibili.Client) *Client
//
// 新增子包后重新运行 go generate ./...，生成物随源码一起提交。
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"
)

// errNotInModule 表示当前目录不在 Go 模块内。
var errNotInModule = errors.New("not inside a Go module")

const generatedHeader = "// Code generated by go run ./internal/cmd/genall; DO NOT EDIT.\n\n"

type pkgInfo struct {
	ImportPath string
	Name       string
	Dir        string
}

type subpackage struct {
	Name  string // 包名
	Field string // 聚合结构体字段名
	Path  string // import 路径
}

func main() {
	out := flag.String("out", "bili/client_gen.go", "生成文件路径，相对模块根")
	flag.Parse()

	if err := run(*out); err != nil {
		_, _ = fmt.Fprintln(os.Stderr, "genall:", err)
		os.Exit(1)
	}
}

func run(out string) error {
	root, err := moduleRoot()
	if err != nil {
		return err
	}
	if err := os.Chdir(root); err != nil {
		return err
	}

	module, err := modulePath()
	if err != nil {
		return err
	}

	pkgs, err := listPackages()
	if err != nil {
		return err
	}

	var subs []subpackage
	for _, p := range pkgs {
		if p.ImportPath == module || p.Name == "bili" || p.Name == "main" ||
			strings.Contains(p.ImportPath, "/internal/") {
			continue
		}
		ok, err := hasConstructor(p.Dir)
		if err != nil {
			return err
		}
		if !ok {
			continue
		}
		subs = append(subs, subpackage{
			Name:  p.Name,
			Field: fieldName(p.Name),
			Path:  p.ImportPath,
		})
	}
	slices.SortFunc(subs, func(a, b subpackage) int { return strings.Compare(a.Name, b.Name) })

	src, err := format.Source(render(module, subs))
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(out), 0o750); err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o600)
}

// moduleRoot 返回 go.mod 所在目录，使生成器从任意工作目录都能运行。
func moduleRoot() (string, error) {
	out, err := exec.Command("go", "env", "GOMOD").Output()
	if err != nil {
		return "", err
	}
	mod := strings.TrimSpace(string(out))
	if mod == "" || mod == os.DevNull {
		return "", errNotInModule
	}
	return filepath.Dir(mod), nil
}

func modulePath() (string, error) {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Path}}").Output()
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(string(out)), nil
}

func listPackages() ([]pkgInfo, error) {
	cmd := exec.Command("go", "list", "-f", "{{.ImportPath}}\t{{.Name}}\t{{.Dir}}", "./...")
	cmd.Stderr = os.Stderr
	raw, err := cmd.Output()
	if err != nil {
		return nil, err
	}

	var pkgs []pkgInfo
	for line := range strings.SplitSeq(strings.TrimSpace(string(raw)), "\n") {
		parts := strings.Split(line, "\t")
		if len(parts) != 3 {
			continue
		}
		pkgs = append(pkgs, pkgInfo{ImportPath: parts[0], Name: parts[1], Dir: parts[2]})
	}
	return pkgs, nil
}

// hasConstructor 判断目录下的 client.go 是否声明了
// func New(*bilibili.Client) *Client。
func hasConstructor(dir string) (bool, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, filepath.Join(dir, "client.go"), nil, 0)
	if err != nil {
		if os.IsNotExist(err) {
			return false, nil
		}
		return false, err
	}

	for _, decl := range file.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Recv != nil || fn.Name.Name != "New" {
			continue
		}
		if fn.Type.Params == nil || len(fn.Type.Params.List) != 1 {
			continue
		}
		if fn.Type.Results == nil || len(fn.Type.Results.List) != 1 {
			continue
		}
		if exprString(fset, fn.Type.Params.List[0].Type) != "*bilibili.Client" {
			continue
		}
		if exprString(fset, fn.Type.Results.List[0].Type) != "*Client" {
			continue
		}
		return true, nil
	}
	return false, nil
}

func exprString(fset *token.FileSet, e ast.Expr) string {
	var buf bytes.Buffer
	if err := format.Node(&buf, fset, e); err != nil {
		return ""
	}
	return buf.String()
}

// wordBreaks 用于把复合包名切成词。新增复合包名时补这里；
// 切不开的包名会整词首字母大写。
var wordBreaks = []string{
	"video", "ranking", "app", "widget", "black", "room",
	"client", "info", "creative", "center", "customer", "service",
	"newbie", "exam", "web",
}

func fieldName(pkg string) string {
	var words []string
	for pkg != "" {
		match := ""
		for _, w := range wordBreaks {
			if strings.HasPrefix(pkg, w) && len(w) > len(match) {
				match = w
			}
		}
		if match == "" {
			words = append(words, pkg)
			break
		}
		words = append(words, match)
		pkg = pkg[len(match):]
	}
	for i, w := range words {
		words[i] = strings.ToUpper(w[:1]) + w[1:]
	}
	return strings.Join(words, "")
}

func render(module string, subs []subpackage) []byte {
	var b bytes.Buffer
	write(&b, generatedHeader)
	write(&b, "package bili\n\n")
	write(&b, "import (\n")
	_, _ = fmt.Fprintf(&b, "\t%q\n", module)
	for _, s := range subs {
		_, _ = fmt.Fprintf(&b, "\t%q\n", s.Path)
	}
	write(&b, ")\n\n")

	write(&b, "// Client 是一个账号的聚合门面。所有域共享同一个根会话。\n")
	write(&b, "type Client struct {\n")
	write(&b, "\t*bilibili.Client\n")
	for _, s := range subs {
		_, _ = fmt.Fprintf(&b, "\t%s *%s.Client\n", s.Field, s.Name)
	}
	write(&b, "}\n\n")

	write(&b, "func newClient(root *bilibili.Client) *Client {\n")
	write(&b, "\treturn &Client{\n")
	write(&b, "\t\tClient: root,\n")
	for _, s := range subs {
		_, _ = fmt.Fprintf(&b, "\t\t%s: %s.New(root),\n", s.Field, s.Name)
	}
	write(&b, "\t}\n}\n")
	return b.Bytes()
}

// write 忽略 bytes.Buffer 的写入错误：它永远返回 nil。
func write(b *bytes.Buffer, s string) {
	_, _ = b.WriteString(s)
}
